template<typename T>
void show_all(std::string_view rem, const T& v)
{
    std::cout << rem << ": ";
    for (const auto& e : v)
        std::cout << e << ' ';
    std::cout << '\n';
}

void setup_io() {
    ios_base::sync_with_stdio(false);
    cin.tie(nullptr);
    #ifdef LOCAL
    freopen("input.txt", "r", stdin);
    freopen("output.txt", "w", stdout);
    #endif
}

int main() {
    setup_io();
    int n;
    cin >> n;

    vi a(n);
    for (auto &x : a) cin >> x;

    vi freq(n + 1, 0);
    ll ans = 1;

    for (int i = 0; i < n; i++) {
        if (i > 0 && a[i] != a[i - 1]) {
            ans += i - freq[a[i]];
        }
        freq[a[i]]++;
    }

    cout << ans << endl;
    return 0;
}
