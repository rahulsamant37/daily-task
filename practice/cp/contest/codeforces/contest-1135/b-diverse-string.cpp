void solve() {
    int n, k;
    cin >> n >> k;

    string least_diverse2;
    cin >> least_diverse2;

    ll cnt1 = count(all(least_diverse2), '1');
    ll cnt0 = n - cnt1;

    ll mx = min((ll)n, max(cnt0, cnt1) + k);
    ll mn = n - mx;

    ll ans = 1 + mx * (mx + 1) / 2 + mn * (mn + 1) / 2;

    cout << ans << endl;
}

